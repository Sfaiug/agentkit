"""A clean plan checkout can use the project's installed Node packages when their inputs match."""

import unittest

from test_key_plan_check_clean_main import PlanHome


class PlanNodeModules(PlanHome):
    def setUp(self):
        self.seat = self._testMethodName
        self.rig = self.project(self.seat, self.seat)
        self.rig.commit({".gitignore": "node_modules/\n", "package.json": "{}\n",
                         "package-lock.json": '{"lockfileVersion": 3}\n',
                         "check.mjs": "import value from 'pkg';\nprocess.exit(value === 42 ? 0 : 1);\n"},
                        "declare packages")
        modules = self.rig.path / "node_modules"
        pkg = modules / "pkg"
        pkg.mkdir(parents=True)
        (pkg / "package.json").write_text('{"main":"index.cjs"}')
        self.entry = pkg / "index.cjs"
        self.entry.write_text("module.exports = 42;\n")
        cli = modules / ".bin" / "pkg-cli"
        cli.parent.mkdir()
        cli.write_text("#!/bin/sh\nexit 0\n")
        cli.chmod(0o755)

    def test_an_import_passes_before_and_after_the_feature_lands(self):
        check = ('test -z "$(git status --porcelain)" && test ! -e node_modules && '
                 'mkdir node_modules && rm -rf node_modules && node check.mjs && pkg-cli && '
                 'test "$(command -v pkg-cli)" = "${PATH##*:}/pkg-cli"')
        self.refused(self.rig, self.seat, "package is usable", check)
        line = self.add(self.rig, self.seat, "feature is available", check + " && test -f feature")
        sha = self.rig.commit({"feature": "ready\n"}, "deliver feature")
        done = self.ak(self.rig, self.seat, "plan")
        self.assertEqual(done.code, 0, done.err)
        self.assertEqual(self.plan(self.seat), [
            line.replace("- [ ]", "- [x]", 1) + f" · done {sha[:12]} deliver feature"])
        self.assertEqual(self.entry.read_text(), "module.exports = 42;\n")

    def test_changed_lockfile_on_main_hides_stale_packages(self):
        self.rig.commit({"package-lock.json": '{"lockfileVersion": 2}\n'}, "change packages")
        self.rig.git("reset", "--hard", "HEAD~1")
        self.refused(self.rig, self.seat, "stale packages are absent",
                     "test ! -e ../node_modules && ! command -v pkg-cli && ! node check.mjs")

    def test_manifest_alone_and_extra_local_lockfiles(self):
        self.rig.commit({"package-lock.json": None}, "use manifest alone")
        self.refused(self.rig, self.seat, "package is usable", "node check.mjs")
        lock = self.rig.path / "bun.lockb"
        lock.touch()
        self.refused(self.rig, self.seat, "uncommitted lock hides packages", "test ! -e ../node_modules")
        lock.unlink()
        manifest = self.rig.path / "package.json"
        manifest.rename(self.home.root / "manifest")
        manifest.symlink_to(self.home.root / "manifest")
        self.refused(self.rig, self.seat, "linked manifest hides packages", "test ! -e ../node_modules")


if __name__ == "__main__":
    unittest.main()
